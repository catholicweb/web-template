// Labels for a language code ("es") or an authored "Label:code" language entry.
// Missing languages (and any missing key) fall back to English.
export function registrationLabels(lang) {
  const code = String(lang ?? "").split(":").pop().slice(0, 2).toLowerCase();
  return { ...EN, ...(REGISTRATION_LABELS[code] ?? {}) };
}
